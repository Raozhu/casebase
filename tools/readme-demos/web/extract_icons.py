"""Generates icons.js from the app's NotchPixelArt.swift, so the web demos draw the exact same icons."""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[3]
source = (ROOT / "casebase/Notch/Components/NotchPixelArt.swift").read_text()


def section(start_marker, end_marker):
    start = source.index(start_marker)
    return source[start:source.index(end_marker, start)]


def names(case_line):
    return re.findall(r"\.(\w+)", case_line)


patterns = {}
body = section("var pattern: [String] {", "var svgSymbol")
for match in re.finditer(r"case ([^:]+):\s*return \[(.*?)\]", body, re.S):
    rows = re.findall(r'"([01]+)"', match.group(2))
    for name in names(match.group(1)):
        patterns[name] = rows

svg = {}
body = section("var svgSymbol: NotchSVGSymbol? {", "struct NotchSVGPathView")
for match in re.finditer(r"case ([^:]+):\s*return NotchSVGSymbol\(\s*pathData: \"([^\"]+)\",\s*renderingMode: ([^\n]+)\n", body):
    mode = match.group(3).strip().rstrip(")").strip()
    stroke = re.match(r"\.stroke\(lineWidth: ([\d.]+), lineCap: \.(\w+)", mode)
    entry = {"d": match.group(2)}
    if stroke:
        entry["stroke"] = float(stroke.group(1))
        entry["cap"] = stroke.group(2)
    for name in names(match.group(1)):
        svg[name] = entry

fonts = {}
body = section("enum NotchPixelFontPattern {", "\n}\n")
for match in re.finditer(r'case "(.)":\s*return \[([^\]]+)\]', body):
    fonts[match.group(1)] = re.findall(r'"([01]+)"', match.group(2))

out = pathlib.Path(__file__).with_name("icons.js")
out.write_text(
    "// Generated by extract_icons.py from casebase/Notch/Components/NotchPixelArt.swift. Do not edit.\n"
    f"export const PIXEL_PATTERNS = {json.dumps(patterns)};\n"
    f"export const SVG_SYMBOLS = {json.dumps(svg)};\n"
    f"export const PIXEL_FONT = {json.dumps(fonts, ensure_ascii=False)};\n"
)
print(f"{len(patterns)} patterns, {len(svg)} svg symbols, {len(fonts)} font glyphs -> {out}")
